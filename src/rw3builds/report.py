"""Data-quality report (Markdown + a minimal HTML rendering of the same content)."""
from __future__ import annotations

import collections
import html
import json
from pathlib import Path

from .catalog import Catalog, catalog_summary
from .models import RecordParse
from .pipeline import REVIEW_FLAG_PREFIXES, Calibration


def _pct(n, d):
    return f"{100 * n / d:.1f}%" if d else "n/a"


def _f(x):
    return "n/a" if x is None else f"{x:.3f}"


def build_report(parses: list[RecordParse], cal: Calibration, cat: Catalog, manifest: dict,
                 evaluation: dict | None) -> str:
    n = len(parses)
    status = collections.Counter(p.parse_status for p in parses)
    victories = [p for p in parses if p.outcome == "VICTORY"]
    sheets = [p for p in parses if p.anchors.get("spell_window") or p.anchors.get("equipment_window")]
    countable = [p for p in parses if p.is_countable]
    with_spells = [p for p in parses if p.spells]
    with_equip = [p for p in parses if p.equipment]
    with_upg = [p for p in parses if any(s.upgrades for s in p.spells)]
    with_unres = [p for p in parses if p.unresolved_upgrades]
    dups = [p for p in parses if p.duplicate_of]
    failed = [p for p in parses if p.parse_status == "failed"]

    spell_items = [s for p in countable for s in p.spells]
    up_items = [u for p in countable for s in p.spells for u in s.upgrades]
    eq_items = [e for p in countable for e in p.equipment]
    unres_items = [u for p in countable for u in p.unresolved_upgrades]
    norm = collections.Counter(pr.normalization for p in countable for coll in (
        [pr for s in p.spells for pr in s.provenance], [pr for s in p.spells for u in s.upgrades for pr in u.provenance],
        [pr for e in p.equipment for pr in e.provenance]) for pr in coll)

    L = ["# RW3 winning-build extraction - data-quality report", "",
         "Generated by `python -m rw3builds run`. Every number below is computed from this run's output.", "",
         "## Sources", "", "| Key | Repo @ commit | sha256 |", "|---|---|---|"]
    for k, m in sorted(manifest.items()):
        where = f"{m.get('repo')} @ `{(m.get('commit') or 'local')[:10]}`" if m.get("repo") else f"local file `{m.get('path')}`"
        L.append(f"| {k} | {where} | `{m['sha256'][:16]}` |")
    cs = catalog_summary(cat)
    L += ["", f"Catalog = union of {len(cat.snapshot_dates)} hpp3/rw3 compendium snapshots "
              f"({cat.snapshot_dates[0]} .. {cat.snapshot_dates[-1]}): " +
          ", ".join(f"{v} {k}" for k, v in cs["by_kind"].items()) + ".",
          f"Upgrade names shared by several spells (never resolved from the name alone): "
          + ", ".join(f"{k} ({len(v)})" for k, v in cs["shared_upgrade_names"].items()) + ".", "",
          "## Coverage (how much was extracted - NOT accuracy)", "",
          "| Measure | Records | Share of all |", "|---|---:|---:|",
          f"| Screenshot records in the raw file | {n} | 100% |",
          f"| Records with a character sheet (Spells/Equipment column anchors) | {len(sheets)} | {_pct(len(sheets), n)} |",
          f"| Recognizable victories (`Outcome: VICTORY`, OCR-tolerant) | {len(victories)} | {_pct(len(victories), n)} |",
          f"| Records with >= 1 extracted spell | {len(with_spells)} | {_pct(len(with_spells), n)} |",
          f"| Records with >= 1 extracted equipment item | {len(with_equip)} | {_pct(len(with_equip), n)} |",
          f"| Records with >= 1 identified upgrade | {len(with_upg)} | {_pct(len(with_upg), n)} |",
          f"| Records with >= 1 unresolved upgrade relationship | {len(with_unres)} | {_pct(len(with_unres), n)} |",
          f"| Suspected duplicate posts (excluded from counts) | {len(dups)} | {_pct(len(dups), n)} |",
          f"| Parsing failures | {len(failed)} | {_pct(len(failed), n)} |",
          f"| **Countable winning builds** (victory + spells + not duplicate) | **{len(countable)}** | {_pct(len(countable), n)} |",
          "", "Record status: " + ", ".join(f"`{k}` {v}" for k, v in sorted(status.items())) + ".", "",
          "- `validated`: no review flag, every upgrade verified, every spell read directly.",
          "- `partial`: some upgrades unresolved, or a spell only implied by its upgrade.",
          "- `needs_review`: at least one review flag (see the review queue).",
          "- `excluded`: not a character sheet (gameplay/combat screenshots), or not a victory.", "",
          "## Item-level summary over countable builds", "",
          f"- Spells: {len(spell_items)} ({sum(s.status == 'owned' for s in spell_items)} read from the Spells column, "
          f"{sum(s.status != 'owned' for s in spell_items)} implied only by an upgrade)",
          f"- Spell-upgrade associations: {len(up_items)} - " + ", ".join(
              f"{k} {v}" for k, v in sorted(collections.Counter(f'{u.association}/{u.method}' for u in up_items).items())),
          f"- Unresolved upgrade relationships: {len(unres_items)} - " + ", ".join(
              f"{k} {v}" for k, v in collections.Counter(u.name for u in unres_items).most_common()),
          f"- Equipment-column items: {len(eq_items)} - " + ", ".join(
              f"{k} {v}" for k, v in sorted(collections.Counter(e.kind for e in eq_items).items())),
          "", "Normalization applied to build items (provenance `normalization` field):", "",
          "| Method | Items |", "|---|---:|"]
    for k, v in norm.most_common():
        L.append(f"| `{k}` | {v} |")

    L += ["", "## Positional association calibration", "",
          "For upgrades whose parent the catalog already fixes, how often would \"the nearest preceding owned "
          "spell in the central Spells column\" have named the right parent?", "",
          f"- Checks: {cal.checks}, correct: {cal.correct}, accuracy: **{_f(cal.accuracy)}** (threshold {cal.threshold})",
          f"- Positional rule enabled: **{cal.positional_enabled}**. " + (
              "Shared-name upgrades with more than one candidate parent in the build are therefore left "
              "**unresolved**, not guessed - the OCR interleaves columns too much for line order to decide."
              if not cal.positional_enabled else "Positional associations are labelled `probable`."), ""]

    L += ["## Accuracy against the hand-annotated gold set", ""]
    if evaluation:
        L += ["Precision/recall of the parser against a human reading of the **same OCR text** (see "
              "`tests/gold/`). The held-out records were annotated before tuning and not used for it. "
              "This cannot detect text the OCR itself dropped.", "",
              "| Split | Records | Spells P / R | Equipment P / R | Spell-upgrade pairs P / R |", "|---|---:|---|---|---|"]
        for split, r in evaluation["by_split"].items():
            L.append(f"| {split} | {r['records']} | {_f(r['spells'].precision)} / {_f(r['spells'].recall)} "
                     f"| {_f(r['equipment'].precision)} / {_f(r['equipment'].recall)} "
                     f"| {_f(r['spell_upgrade_pairs'].precision)} / {_f(r['spell_upgrade_pairs'].recall)} |")
        if evaluation["errors"]:
            L += ["", "Gold-set disagreements:", "", "| Record | Split | Kind | Error | Item |", "|---|---|---|---|---|"]
            for e in evaluation["errors"]:
                item = "::".join(e["item"]) if isinstance(e["item"], tuple) else e["item"]
                L.append(f"| `{e['record_id']}` | {e['split']} | {e['kind']} | {e['error']} | {item} |")
    else:
        L.append("_No gold set found._")

    flags = collections.Counter(f.split(":", 1)[0] for p in parses for f in p.flags)
    L += ["", "## Flags", "", "| Flag | Occurrences | Review? |", "|---|---:|---|"]
    for k, v in flags.most_common():
        L.append(f"| `{k}` | {v} | {'yes' if (k + ':').startswith(REVIEW_FLAG_PREFIXES) or k.startswith(REVIEW_FLAG_PREFIXES) else ''} |")

    unk = collections.Counter(u.raw_text.strip() for p in countable for u in p.unknown_tokens
                              if u.name_like and u.zone != "outside")
    L += ["", "## Unrecognized name-like lines inside the build columns (top 50, countable builds)", "",
          "Mostly halves of names the narrow panes wrapped onto two lines, where several catalog names share "
          "the half (e.g. `Staff`, `Rift`). They are kept in `unknown_token` and never become build items.", "",
          "| Text | Occurrences |", "|---|---:|"]
    for k, v in unk.most_common(50):
        L.append(f"| `{k}` | {v} |")

    oos = collections.Counter(m.provenance.rule for p in countable for m in p.out_of_scope_mentions)
    L += ["", "## Catalog names seen outside the build columns (never counted)", "",
          "| Rule | Mentions |", "|---|---:|"]
    for k, v in oos.most_common():
        L.append(f"| `{k}` | {v} |")

    review = [p for p in parses if p.parse_status in ("needs_review", "failed")]
    L += ["", f"## Manual-review queue ({len(review)} records)", "",
          "| Record | Status | Reasons |", "|---|---|---|"]
    for p in sorted(review, key=lambda p: p.record_id):
        reasons = sorted({f for f in p.flags if f.startswith(REVIEW_FLAG_PREFIXES) or f == "no_spells_extracted"})
        L.append(f"| `{p.record_id}` | {p.parse_status} | {'; '.join(reasons)[:400]} |")
    excl = [p for p in parses if p.parse_status == "excluded"]
    L += ["", f"## Excluded records ({len(excl)})", "", "| Record | Reason |", "|---|---|"]
    for p in excl:
        L.append(f"| `{p.record_id}` | {'; '.join(f for f in p.flags if f.startswith('excluded'))} |")
    return "\n".join(L) + "\n"


def markdown_to_html(md: str, title: str) -> str:
    """Tiny renderer for the report's own subset (headings, tables, lists, code, bold)."""
    import re
    out, in_table, in_list = [], False, False

    def inline(s):
        s = html.escape(s)
        s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
        s = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", s)
        s = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', s)
        return s

    for line in md.splitlines():
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if all(set(c) <= set("-: ") for c in cells):
                continue
            if not in_table:
                out.append("<table>")
                in_table = True
                out.append("<tr>" + "".join(f"<th>{inline(c)}</th>" for c in cells) + "</tr>")
            else:
                out.append("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in cells) + "</tr>")
            continue
        if in_table:
            out.append("</table>")
            in_table = False
        if line.startswith("- ") or line.startswith("  - "):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{inline(line.lstrip(' -'))}</li>")
            continue
        if in_list:
            out.append("</ul>")
            in_list = False
        if line.startswith("#"):
            lvl = len(line) - len(line.lstrip("#"))
            out.append(f"<h{lvl}>{inline(line.lstrip('# '))}</h{lvl}>")
        elif line.strip():
            out.append(f"<p>{inline(line)}</p>")
    if in_table:
        out.append("</table>")
    if in_list:
        out.append("</ul>")
    css = ("body{font:14px/1.45 system-ui,sans-serif;max-width:1100px;margin:2em auto;padding:0 16px;"
           "background:#fff;color:#1a1a1a}table{border-collapse:collapse;margin:1em 0}td,th{border:1px solid #ccc;"
           "padding:3px 8px;text-align:left;vertical-align:top}code{background:#f2f2f2;padding:0 3px}"
           "@media (prefers-color-scheme: dark){body{background:#161616;color:#e6e6e6}td,th{border-color:#444}code{background:#2a2a2a}}")
    return (f"<!doctype html><html><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'>"
            f"<title>{html.escape(title)}</title><style>{css}</style></head><body>" + "\n".join(out) + "</body></html>\n")
